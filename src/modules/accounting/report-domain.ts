import { addDays, validDay } from "../menu/domain.ts";
import { monthRange } from "../billing/domain.ts";
import type { BcContent } from "../production/domain.ts";

export type BcReportDocument = { id: string; number: string; issueDate: string; kind: string; content: BcContent };

export function weekRange(day: string) {
  if (!validDay(day)) throw new Error("ACCOUNTING_REPORT_DATE");
  const weekday = new Date(day + "T12:00:00Z").getUTCDay();
  const from = addDays(day, -((weekday + 6) % 7));
  return { from, to: addDays(from, 6) };
}

export function monthWeeks(period: string) {
  const month = monthRange(period);
  const weeks: { from: string; to: string }[] = [];
  for (let day = month.from; day <= month.to;) {
    const week = weekRange(day);
    weeks.push({ from: day, to: week.to < month.to ? week.to : month.to });
    day = addDays(week.to, 1);
  }
  return weeks;
}

export function accountingDeadline(period: string) {
  const month = monthRange(period);
  return addDays(month.to, 1).slice(0, 8) + "10";
}

/** Include original documents even when reversed, and signed reversals on their own issue date. */
export function summarizeConsumption(documents: BcReportDocument[]) {
  const seen = new Set<string>();
  const totals = new Map<string, { name: string; unit: string; quantity: number; value: number }>();
  let total = 0;
  for (const document of documents) {
    if (seen.has(document.id)) continue;
    seen.add(document.id);
    total += document.content.totalValue;
    for (const line of document.content.lines) {
      const key = JSON.stringify([line.ingredientId, line.name, line.unit]);
      const value = totals.get(key) ?? { name: line.name, unit: line.unit, quantity: 0, value: 0 };
      value.quantity += line.quantity;
      value.value += line.value;
      totals.set(key, value);
    }
  }
  return { lines: [...totals.values()].sort((a, b) => a.name.localeCompare(b.name, "ro")), total, count: seen.size };
}

export const escapeReport = (value: unknown) => String(value ?? "").replace(/[&<>"']/g, (character) =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[character]!);
export const reportLei = (bani: number) => (bani / 100).toLocaleString("ro-RO", { minimumFractionDigits: 2, maximumFractionDigits: 2 });

export function consumptionSection(from: string, to: string, documents: BcReportDocument[]) {
  const summary = summarizeConsumption(documents);
  const rows = summary.lines.map((line) => {
    const factor = line.unit === "g" || line.unit === "ml" ? 1000 : 1;
    const unit = line.unit === "g" ? "kg" : line.unit === "ml" ? "l" : line.unit;
    return `<tr><td>${escapeReport(line.name)}</td><td>${escapeReport(unit)}</td><td class="n">${(line.quantity / factor).toLocaleString("ro-RO", { maximumFractionDigits: 3 })}</td><td class="n">${reportLei(line.value)}</td></tr>`;
  }).join("");
  const sources = documents.map((document) => `<li>${escapeReport(document.number)} · ${document.issueDate}${document.kind === "reversal" ? " · STORNO" : ""}</li>`).join("");
  return `<h1>CENTRALIZATOR BONURI DE CONSUM</h1><p>${from} – ${to}</p>
    <table><thead><tr><th>Materie primă</th><th>U.M.</th><th>Cantitate</th><th>Valoare (lei)</th></tr></thead><tbody>${rows || '<tr><td colspan="4">Fără documente în această perioadă.</td></tr>'}</tbody>
    <tfoot><tr><td colspan="3">Total din documentele sursă</td><td class="n">${reportLei(summary.total)}</td></tr></tfoot></table>
    <h2>Documente sursă (${summary.count})</h2><ul>${sources}</ul><p>Valorile și denumirile provin din documentele emise. Stornările sunt incluse la data emiterii lor.</p>`;
}

/** Only used with HTML generated by the application's own document renderers. */
export function reportDocumentBody(html: string) {
  const body = /<body[^>]*>([\s\S]*)<\/body>/i.exec(html);
  if (!body) throw new Error("ACCOUNTING_DOCUMENT_FORMAT");
  return body[1];
}

